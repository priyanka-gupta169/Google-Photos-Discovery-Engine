def get_representative_dataset() -> List[RepresentativePhoto]:
    """Returns the full controlled representative dataset of 40 photos."""
    return REPRESENTATIVE_DATASET


def get_photo_by_id(photo_id: str) -> Optional[RepresentativePhoto]:
    """Retrieves a single photo by its unique identifier."""
    for p in REPRESENTATIVE_DATASET:
        if p.id == photo_id:
            return p
    return None


def get_photos_for_task(task_id: str) -> List[RepresentativePhoto]:
    """Retrieves ground-truth and associated distractor photos for an evaluation task."""
    return [p for p in REPRESENTATIVE_DATASET if p.ground_truth_task_id == task_id or (p.is_distractor and task_id in (p.ground_truth_task_id or ""))]
